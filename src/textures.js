function imageAsset(path){
 if(!assets[path]){
  const img=new Image();
  assets[path]=img;
  img.onload=()=>preloadCount++;
  img.onerror=()=>{
   console.error('Recurso indisponível:',path);
   $('stateText').textContent='Recurso indisponível: '+path;
  };
  const clean=cleanedPneusonTextures.has(path)?path.replace(/\.png$/,'_clean.png'):path;
  const texture=matchedPaletteTextures.has(clean)?clean.replace(/\.png$/,'_palette.png'):clean;
  const name=texture.slice('assets/fighters/'.length,-4);
  img.src=texture.startsWith('assets/fighters/')&&debrisCleanedTextures.has(name)?
   texture.replace(/\.png$/,'_tidy.png'):texture;
 }
 return assets[path];
}
